export const getCountryName = (code: CountryCode, locale: string = 'es'): string => {
  return countries[code]?.[locale] ?? countries[code]?.['en'] ?? code
}

export const getAllCountries = (locale: string = 'es'): CountryEntry[] => {
  return Object.entries(countries).map(([code, names]) => ({
    code,
    name: { en: names.en, es: names.es }
  }))
}

export const getCountryNames = (locale: string = 'es'): Record<CountryCode, string> => {
  const result: Record<string, string> = {}
  for (const [code, names] of Object.entries(countries)) {
    result[code] = names[locale] ?? names['en'] ?? code
  }
  return result
}

export default countries
