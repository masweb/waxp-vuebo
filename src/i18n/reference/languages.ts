export const getLanguageName = (code: LanguageCode, locale: string = 'es'): string => {
  return languages[code]?.[locale] ?? languages[code]?.['en'] ?? code
}

export const getAllLanguages = (locale: string = 'es'): LanguageEntry[] => {
  return Object.entries(languages).map(([code, names]) => ({
    code,
    name: { en: names.en, es: names.es }
  }))
}

export const getLanguageNames = (locale: string = 'es'): Record<LanguageCode, string> => {
  const result: Record<string, string> = {}
  for (const [code, names] of Object.entries(languages)) {
    result[code] = names[locale] ?? names['en'] ?? code
  }
  return result
}

export default languages
